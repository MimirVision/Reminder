// Bundles each edge function (index.ts + logic.ts) into ONE file that can be pasted into the Supabase dashboard
// editor (Edge Functions > Deploy a new function > Via Editor), for people without the Supabase CLI.
import { readFileSync, writeFileSync } from 'node:fs';

export const FUNCTIONS = ['suggest', 'import-report', 'notify-partner', 'read-label', 'parse-tasks', 'post-alerts'];

/**
 * Files a function shares with another part of the repo. They are generated from their source, never edited here, so the Post app and its
 * alert server cannot drift apart: both sort mail with the very same text. `to` is where the copy for the CLI lives next to the function.
 */
export const SHARED = {
  classify: {
    function: 'post-alerts',
    file: 'classify.ts',
    from: new URL('../apps/web/src/post/core/classify.ts', import.meta.url),
    types: new URL('../apps/web/src/post/core/types.ts', import.meta.url),
  },
};

/** The text of a shared file as the function sees it: the app's file, with its one import of the app's `Kind` type written out. */
export function shared(name) {
  const s = SHARED[name];
  const src = readFileSync(s.from, 'utf8');
  const kind = /^export type Kind = [^;]+;$/m.exec(readFileSync(s.types, 'utf8'))?.[0];
  if (!kind) throw new Error('types.ts no longer has a one-line "export type Kind = ...;"');
  const imp = "import type { Kind } from './types.ts';";
  if (!src.includes(imp)) throw new Error(`${name}: the import of Kind changed, update build-functions.mjs`);
  return [
    `// GENERATED by supabase/build-functions.mjs from apps/web/src/post/core/${s.file}. Do not edit by hand: the Post app and its alert server must sort mail the same way.`,
    src.replace(imp, kind),
  ].join('\n');
}

export function bundle(name) {
  const dir = new URL(`./functions/${name}/`, import.meta.url);
  const logicLines = readFileSync(new URL('logic.ts', dir), 'utf8').trimEnd().split('\n');
  const indexLines = readFileSync(new URL('index.ts', dir), 'utf8').split('\n');
  const isLogicImport = (l) => /^import\b.*from '\.\/logic\.ts';\s*$/.test(l);
  // A function may reuse another function's logic (post-alerts sends Web Push with notify-partner's code): inline it once.
  const depOf = (l) => /^import\b.*from '\.\.\/([a-z-]+)\/logic\.ts';\s*$/.exec(l)?.[1];
  const deps = [...new Set([...logicLines, ...indexLines].map(depOf).filter(Boolean))];
  const depLogic = deps.flatMap((d) => [`// ---- logic (${d}) ----`, readFileSync(new URL(`../${d}/logic.ts`, dir), 'utf8').trimEnd(), '']);
  // ... or a file generated from somewhere else in the repo (see SHARED): inline that too.
  const sharedOf = (l) => { const n = /^import\b.*from '\.\/([a-z-]+)\.ts';\s*$/.exec(l)?.[1]; return n && SHARED[n]?.function === name ? n : undefined; };
  const sharedFiles = [...new Set([...logicLines, ...indexLines].map(sharedOf).filter(Boolean))];
  const sharedCode = sharedFiles.flatMap((n) => [`// ---- shared with the Post app (${n}) ----`, shared(n).trimEnd(), '']);
  const logic = logicLines.filter((l) => !depOf(l) && !sharedOf(l)).join('\n');
  const header = indexLines.filter((l, i) => i < 4 && l.startsWith('//'));
  const imports = indexLines.filter((l) => /^import\b/.test(l) && !isLogicImport(l) && !depOf(l) && !sharedOf(l));
  const handler = indexLines.filter((l) => !/^import\b/.test(l)).slice(header.length).join('\n').replace(/^\n+/, '');
  return [
    `// GENERATED by supabase/build-functions.mjs from functions/${name}/{index,logic}.ts. Do not edit by hand.`,
    `// Paste this whole file into the Supabase dashboard editor for a function named "${name}".`,
    ...header, ...imports, '', ...depLogic, ...sharedCode, '// ---- logic ----', logic, '', '// ---- handler ----',
    handler, '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const n of FUNCTIONS) writeFileSync(new URL(`./dashboard/${n}.ts`, import.meta.url), bundle(n));
  for (const [n, s] of Object.entries(SHARED)) writeFileSync(new URL(`./functions/${s.function}/${s.file}`, import.meta.url), shared(n));
  console.log('wrote supabase/dashboard/*.ts and the shared copies in supabase/functions/*/');
}
