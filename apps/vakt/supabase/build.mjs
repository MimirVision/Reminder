// Concatenates Vakt's migrations into vakt.sql: one file to paste into the Supabase SQL editor.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

export function buildVaktSql() {
  const dir = new URL('./migrations/', import.meta.url);
  const parts = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
    .map((f) => `-- ===== ${f} =====\n${readFileSync(new URL(f, dir), 'utf8').trim()}\n`);
  return `-- Generated by apps/vakt/supabase/build.mjs. Vakt's tables and functions only (all named vakt_*).
-- Paste into Supabase > SQL Editor > New query, then Run. Safe to run again; it never touches the other apps.

${parts.join('\n')}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('./vakt.sql', import.meta.url), buildVaktSql());
  console.log('wrote apps/vakt/supabase/vakt.sql');
}
