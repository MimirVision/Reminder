// Concatenates Ledger's migrations into ledger.sql: one file to paste into the Supabase SQL editor.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

export function buildLedgerSql() {
  const dir = new URL('./migrations/', import.meta.url);
  const parts = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
    .map((f) => `-- ===== ${f} =====\n${readFileSync(new URL(f, dir), 'utf8').trim()}\n`);
  return `-- Generated by apps/ledger/supabase/build.mjs. Ledger's tables and functions only (all named ledger_*).
-- Paste into Supabase > SQL Editor > New query, then Run. Safe to run again; it never touches Home Memory or Post.

${parts.join('\n')}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('./ledger.sql', import.meta.url), buildLedgerSql());
  console.log('wrote apps/ledger/supabase/ledger.sql');
}
