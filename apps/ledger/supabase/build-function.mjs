// Bundles the ledger-notify edge function (index.ts, plan.ts, push.ts and the app's src/lib/reminders.ts) into ONE file to paste
// into the Supabase dashboard (Edge Functions > Deploy a new function > Via Editor). The app and the function then share the
// very same reminder rules. A test fails if dashboard/ledger-notify.ts is stale: run `npm run build:function`.
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('./functions/ledger-notify/', import.meta.url);
const read = (rel) => readFileSync(new URL(rel, dir), 'utf8').trimEnd().split('\n');
const isLocalImport = (l) => /^import\b.*from '\.{1,2}\/[^']+';\s*$/.test(l);

export function bundleNotify() {
  const parts = [['src/lib/reminders.ts', '../../../src/lib/reminders.ts'], ['plan.ts', 'plan.ts'], ['push.ts', 'push.ts']];
  const index = read('index.ts');
  const header = index.filter((l, i) => i < 4 && l.startsWith('//'));
  const imports = index.filter((l) => /^import\b/.test(l) && !isLocalImport(l));
  const body = (lines) => lines.filter((l) => !isLocalImport(l));
  for (const [, rel] of parts) {
    const other = read(rel).find((l) => /^import\b/.test(l) && !isLocalImport(l) && !/^import type\b/.test(l));
    if (other) throw new Error(`${rel} imports a package (${other}); add it to the bundle header`);
  }
  return [
    '// GENERATED by apps/ledger/supabase/build-function.mjs. Do not edit by hand.',
    '// Paste this whole file into the Supabase dashboard editor for a function named "ledger-notify".',
    ...header, ...imports, '',
    ...parts.flatMap(([name, rel]) => [`// ---- ${name} ----`, ...body(read(rel)), '']),
    '// ---- handler ----', ...index.filter((l) => !/^import\b/.test(l)).slice(header.length).join('\n').replace(/^\n+/, '').split('\n'), '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('./dashboard/ledger-notify.ts', import.meta.url), bundleNotify());
  console.log('wrote apps/ledger/supabase/dashboard/ledger-notify.ts');
}
